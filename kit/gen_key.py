#!/usr/bin/env python3
"""Generate the pre-shared key for one AP_MAVCrypt algorithm.

Writes keys/<alg>.key (hex, used by the PC proxy) and keys/mavcrypt_key.h
(compiled into ArduPilot by drone/apply_mavcrypt.py -- regenerate and
re-apply when switching the algorithm you are about to build). Both are
secret: keys/ is excluded from Git.

A new key invalidates every binary built with the old one, so an existing
keys/<alg>.key is never overwritten unless --force is given.
"""
import argparse
import os
import secrets
import sys

KIT = os.path.dirname(os.path.abspath(__file__))
KEY_DIR = os.path.join(KIT, "keys")

# must match MC_KEY_LEN in kit/common/mavcrypt_core.h for each AP_MAVCRYPT_ALG
KEY_BYTES = {"ascon": 16, "aesgcm": 16, "chacha": 32}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--alg", choices=sorted(KEY_BYTES), default="ascon")
    ap.add_argument("--force", action="store_true", help="overwrite an existing key")
    args = ap.parse_args()
    klen = KEY_BYTES[args.alg]

    key_path = os.path.join(KEY_DIR, f"{args.alg}.key")
    hdr_path = os.path.join(KEY_DIR, "mavcrypt_key.h")
    if os.path.exists(key_path) and not args.force:
        key = bytes.fromhex(open(key_path).read().strip())
        print(f"[keep] {key_path} already exists (use --force to replace it)")
    else:
        os.makedirs(KEY_DIR, exist_ok=True)
        key = secrets.token_bytes(klen)
        fd = os.open(key_path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w") as f:
            f.write(key.hex() + "\n")
        print(f"[new]  {key_path}")

    if len(key) != klen:
        sys.exit(f"{args.alg}: key must be {klen} bytes")
    body = ", ".join(f"0x{b:02x}" for b in key)
    with open(hdr_path, "w", newline="\n") as f:
        f.write(f"// Generated by kit/gen_key.py --alg {args.alg} - SECRET, do not commit\n")
        f.write("#pragma once\n#include <stdint.h>\n")
        f.write(f"static const uint8_t MAVCRYPT_KEY[{klen}] = {{{body}}};\n")
    os.chmod(hdr_path, 0o600)
    print(f"[ok]   {hdr_path} (alg={args.alg}, {klen}-byte key)")
    # fingerprint lets you check that drone and PC use the same key without revealing it
    import hashlib
    print(f"key fingerprint (sha256, first 8 hex): {hashlib.sha256(key).hexdigest()[:8]}")


if __name__ == "__main__":
    main()
